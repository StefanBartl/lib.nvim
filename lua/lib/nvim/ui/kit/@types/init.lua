--- Options for `kit.chip.mount`.
---@class Lib.UI.Kit.ChipOpts
---@field id string                              # stable key; a second `mount` with the same id re-configures it
---@field text? string|fun():string              # re-read on every `refresh`; "" hides the chip; embed `\n` for a multi-line box (height follows the line count)
---@field visible? boolean|fun():boolean         # default: derived from `text` being non-empty
---@field anchor? "bottom-left"|"bottom-right"|"top-left"|"top-right"  # default "bottom-left"
---@field shape? Lib.UI.Kit.Preset|"dock_left"       # default "rounded_chip"; "classic" has no box at all (no border, no background); "dock_left" rounds every corner but the left one (see `dock`); old names ("rounded"/"rect"/"text") still accepted, see lib.nvim.ui.kit.presets
---@field color? Lib.UI.Kit.ChipColor
---@field zindex? integer                        # default 60
---@field dock? boolean                          # sit flush ON the statusline row (col 0, no gap) instead of floating just above it; degrades to the ordinary placement when there is no statusline row to dock against (`laststatus = 0`, or none active). Meant to pair with `shape = "dock_left"`, but independent of it.
---@field track_mode? boolean                    # refresh() this one chip on every `ModeChanged`, e.g. for a `color` function that tracks the current mode -- opt-in per chip, not a blanket autocmd
---@field row_offset? integer                    # default 0; added to the computed row after anchor/dock placement -- a plain per-chip nudge, e.g. to compensate for a specific host terminal's own rendering quirks without hardcoding that terminal's name anywhere in this module. Note: Neovim floating windows are clipped to the actual terminal grid -- a terminal's own OUTER padding (applied around that grid, e.g. WezTerm's `window_padding`) sits entirely outside anything a `col`/`row` value can reach, so this cannot compensate for that specific class of gap; it only ever repositions the chip within the grid Neovim can already draw into. Accepts a fractional number, but `:h nvim_open_win()`'s own `row`/`col` are documented to always round DOWN to the nearest integer in Neovim's builtin (non-multigrid) implementation -- the one a plain terminal client uses -- so e.g. `0.5` renders pixel-identical to `0`, not "half a cell". Pass an integer; a fractional value is accepted but never actually more precise than `math.floor()` of it.
---@field col_offset? integer                    # default 0; same as `row_offset`, applied to the computed column. Same clipped-to-the-grid and floor-to-integer caveats apply.
---@field min_width? integer                     # default 0 (no minimum); a floor under the box's normally content-derived width (longest rendered line + 2). Content wider than it still grows the box past it -- this only stops a short line (e.g. one glyph plus a mode letter) from rendering visibly cramped. Floored to a non-negative integer; an invalid value (non-number, NaN, +-Infinity, negative) sanitizes to 0 rather than crashing `mount()`.

